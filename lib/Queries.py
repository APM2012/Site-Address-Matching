"""Synthetic example SQL for the portfolio demo.

These queries illustrate the shape of a clinical operations warehouse without
using employer-specific schemas or real study identifiers.
"""

EXAMPLE_STUDY = "DEMO-STUDY-001"
EXAMPLE_DATABASE = "EXAMPLE_DATA.DIS_VVC_OUT_VIEWS"


us_site_info = f"""
SELECT mv.STUDY_NUMBER,
       mv.STUDY_COUNTRY,
       mv.STUDY_SITE_NUMBER,
       'Example Study' AS STUDY_NAME,
       ssv.MAIN_INVESTIGATIONAL_SITE,
       spv.PERSON,
       ssv.STATUS,
       enr.SITE_ACTUAL_SCREENED,
       enr.SITE_ACTUAL_ENROLLED,
       mv.ACTUAL_FINISH_DATE AS SITE_ACTIVATED
FROM {EXAMPLE_DATABASE}.MILESTONE_V1_0 mv
LEFT JOIN {EXAMPLE_DATABASE}.STUDY_SITE_V1_0 ssv
  ON mv.STUDY_SITE_NUMBER = ssv.STUDY_SITE_NUMBER
LEFT JOIN {EXAMPLE_DATABASE}.STUDY_PERSON_V1_0 spv
  ON mv.STUDY_SITE_NUMBER = spv.STUDY_SITE_NUMBER
 AND mv.STUDY_NUMBER = spv.STUDY_NUMBER
LEFT JOIN (
    SELECT STUDY_SITE_NUMBER,
           COUNT(ssv.SCREENING_VISIT_DATE) AS SITE_ACTUAL_SCREENED,
           COUNT(ssv.ENROLLED_DATE) AS SITE_ACTUAL_ENROLLED
    FROM {EXAMPLE_DATABASE}.STUDY_SUBJECT_V1_0 ssv
    WHERE ssv.STUDY_NUMBER = '{EXAMPLE_STUDY}'
    GROUP BY STUDY_SITE_NUMBER
) enr
  ON mv.STUDY_SITE_NUMBER = enr.STUDY_SITE_NUMBER
WHERE mv.STUDY_NUMBER = '{EXAMPLE_STUDY}'
  AND mv.MILESTONE_TYPE = 'Site Activated'
  AND mv.ACTUAL_FINISH_DATE IS NOT NULL
  AND mv.STUDY_COUNTRY = 'United States'
  AND spv.STUDY_TEAM_ROLE = 'Principal Investigator'
  AND spv.LIFECYCLE_STATE = 'Active'
ORDER BY mv.STUDY_SITE_NUMBER"""


us_overall_info = f"""
WITH source_text AS (
    SELECT TO_VARCHAR(ssv.SCREENING_VISIT_DATE, 'yyyy-mm') AS SCREENING,
           TO_VARCHAR(ssv.ENROLLED_DATE, 'yyyy-mm') AS ENROLLED
    FROM {EXAMPLE_DATABASE}.STUDY_SUBJECT_V1_0 ssv
    WHERE ssv.STUDY_NUMBER = '{EXAMPLE_STUDY}'
      AND ssv.STUDY_COUNTRY = 'United States'
      AND ssv.SCREENING_VISIT_DATE IS NOT NULL
)
SELECT SCREENING AS MONTH,
       COUNT(SCREENING) AS SCREENED,
       COUNT(ENROLLED) AS ENROLLED
FROM source_text
GROUP BY SCREENING"""


us_planned_activation = f"""
SELECT mv.STUDY_SITE_NUMBER,
       mv.PLANNED_FINISH_DATE AS PLANNED_SITE_ACTIVATED
FROM {EXAMPLE_DATABASE}.MILESTONE_V1_0 mv
WHERE mv.STUDY_NUMBER = '{EXAMPLE_STUDY}'
  AND mv.MILESTONE_TYPE = 'Site Activated'
  AND mv.PLANNED_FINISH_DATE IS NOT NULL
  AND mv.STUDY_COUNTRY = 'United States'
ORDER BY mv.STUDY_NUMBER, mv.STUDY_SITE_NUMBER"""


us_subject_summary = f"""
SELECT ssv.STUDY_SITE_NUMBER,
       ssv.SUBJECT_ID,
       IFF(ssv.SUBJECT_STATUS = 'Pre-screening'
           AND ssvv.PRESCREENING_FAILED_DATE IS NOT NULL,
           'Pre-screening Failure',
           ssv.SUBJECT_STATUS) AS SUBJECT_STATUS,
       ssvv.PRESCREENING_DATE,
       ssvv.PRESCREENING_FAILED_DATE,
       ssv.SCREENING_VISIT_DATE,
       ssv.RESCREENING_VISIT_DATE,
       ssv.SCREENING_FAILURE_DATE,
       ssv.ENROLLED_DATE
FROM {EXAMPLE_DATABASE}.STUDY_SUBJECT_V1_0 ssv
LEFT JOIN (
    SELECT SUBJECT_ID,
           MAX(IFF(VISIT_NAME = 'Pre-screen Failed', ACTUAL_VISIT_DATE, NULL)) AS PRESCREENING_FAILED_DATE,
           MAX(IFF(VISIT_NAME = 'Central Pre-screening', ACTUAL_VISIT_DATE, NULL)) AS PRESCREENING_DATE
    FROM {EXAMPLE_DATABASE}.STUDY_SUBJECT_VISIT_V1_0
    WHERE STUDY_COUNTRY = 'United States'
      AND STUDY_NUMBER = '{EXAMPLE_STUDY}'
    GROUP BY SUBJECT_ID
) ssvv ON ssv.ID = ssvv.SUBJECT_ID
WHERE ssv.STUDY_NUMBER = '{EXAMPLE_STUDY}'
  AND ssv.STUDY_COUNTRY = 'United States'"""


vvc_timestamp = f"""
SELECT TO_DATE(ssv.LOAD_TIMESTAMP) AS stamp
FROM {EXAMPLE_DATABASE}.STUDY_SUBJECT_V1_0 ssv
WHERE ssv.STUDY_NUMBER = '{EXAMPLE_STUDY}'
LIMIT 1"""


